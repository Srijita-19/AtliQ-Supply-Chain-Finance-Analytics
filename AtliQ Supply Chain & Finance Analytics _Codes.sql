-- Q2) Customer Segmentation
WITH CustomerSales AS
(
    SELECT
        c.customer_code,
        c.customer,
        c.channel,
        c.market,
        c.region,
        SUM(s.sold_quantity) AS total_quantity,
        COUNT(DISTINCT s.date) AS purchase_months,
        SUM(s.sold_quantity * ISNULL(gp.gross_price,0)) AS gross_revenue
    FROM dim_customer c
    LEFT JOIN fact_sales_monthly s
        ON c.customer_code = s.customer_code
    LEFT JOIN fact_gross_price gp
        ON s.product_code = gp.product_code
       AND dbo.fn_GetFiscalYear(s.date) = gp.fiscal_year
    GROUP BY c.customer_code, c.customer, c.channel, c.market, c.region
)
SELECT *,
       CASE
         WHEN total_quantity >= 1000 THEN 'High Value'
         WHEN total_quantity >= 500 THEN 'Medium Value'
         ELSE 'Low Value'
       END AS customer_segment
FROM CustomerSales
ORDER BY gross_revenue DESC;
-- Q3) Product Performance Comparison
SELECT
    p.product_code,
    p.product,
    p.variant,
    SUM(s.sold_quantity) AS total_sales_quantity,
    SUM(s.sold_quantity * ISNULL(gp.gross_price,0)) AS gross_revenue,
    RANK() OVER
      (ORDER BY SUM(s.sold_quantity * ISNULL(gp.gross_price,0)) DESC) AS revenue_rank
FROM dim_product p
LEFT JOIN fact_sales_monthly s
    ON p.product_code = s.product_code
LEFT JOIN fact_gross_price gp
    ON s.product_code = gp.product_code
   AND dbo.fn_GetFiscalYear(s.date) = gp.fiscal_year
GROUP BY p.product_code, p.product, p.variant
ORDER BY revenue_rank;
