-- Q5) Cost Analysis
SELECT
    p.product_code,
    p.product,
    mc.cost_year,
    mc.manufacturing_cost,
    gp.gross_price,
    gp.gross_price - mc.manufacturing_cost AS gross_profit_per_unit,
    CASE
      WHEN gp.gross_price > 0
      THEN ((gp.gross_price - mc.manufacturing_cost) / gp.gross_price) * 100
      ELSE NULL
    END AS profit_margin_pct
FROM dim_product p
JOIN fact_manufacturing_cost mc
  ON p.product_code = mc.product_code
JOIN fact_gross_price gp
  ON mc.product_code = gp.product_code
 AND mc.cost_year = gp.fiscal_year
ORDER BY profit_margin_pct DESC;
