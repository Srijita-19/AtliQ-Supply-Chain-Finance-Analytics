CREATE TABLE fact_freight_cost (
    market VARCHAR(45) NOT NULL,
    fiscal_year INT NOT NULL,
    freight_pct DECIMAL(5,4),
    other_cost_pct DECIMAL(5,4),
    CONSTRAINT PK_fact_freight_cost PRIMARY KEY (market, fiscal_year)
    CONSTRAINT CK_forecast_quantity_nonnegative
