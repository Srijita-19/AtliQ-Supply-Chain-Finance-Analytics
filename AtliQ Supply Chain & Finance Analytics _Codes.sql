-- HELPER FUNCTION
-- Fiscal year starts in September and ends in August.
-- ============================================================================
CREATE FUNCTION dbo.fn_GetFiscalYear (@calendar_date DATE)
RETURNS INT
AS
BEGIN
    RETURN CASE
             WHEN MONTH(@calendar_date) >= 9 THEN YEAR(@calendar_date) + 1
             ELSE YEAR(@calendar_date)
           END;
END;

