CREATE TRIGGER trg_FlagSalesOutliers
ON fact_sales_monthly
AFTER INSERT
AS
BEGIN
    SET NOCOUNT ON;

    ;WITH ProductStats AS
    (
        SELECT
            s.product_code,
            s.date,
            SUM(s.sold_quantity) AS monthly_quantity,
            AVG(CAST(SUM(s.sold_quantity) AS FLOAT))
                OVER (PARTITION BY s.product_code) AS avg_quantity,
            STDEV(CAST(SUM(s.sold_quantity) AS FLOAT))
                OVER (PARTITION BY s.product_code) AS std_quantity
        FROM fact_sales_monthly s
        GROUP BY s.product_code, s.date
    ),
    InsertedMonths AS
    (
        SELECT DISTINCT product_code, date
        FROM inserted
    )
    INSERT INTO sales_outlier_log
    (sales_date, product_code, sold_quantity, average_quantity,
     standard_deviation, flag)
    SELECT
        ps.date,
        ps.product_code,
        ps.monthly_quantity,
        ps.avg_quantity,
        ISNULL(ps.std_quantity,0),
        'OUTLIER'
    FROM ProductStats ps
    JOIN InsertedMonths im
      ON ps.product_code = im.product_code
     AND ps.date = im.date
    WHERE ps.std_quantity IS NOT NULL
      AND ABS(ps.monthly_quantity - ps.avg_quantity)
            > (2 * ps.std_quantity);
END;
