DECLARE @CustomerCode BIGINT = 70002017;
DECLARE @FiscalYear INT = 2018;

SELECT s.date, s.product_code, p.product, p.variant, s.sold_quantity, gp.gross_price, s.sold_quantity * gp.gross_price AS gross_price_total FROM fact_sales_monthly s
INNER JOIN dim_product p
    ON s.product_code = p.product_code
INNER JOIN fact_gross_price gp
    ON s.product_code = gp.product_code
   AND dbo.fn_GetFiscalYear(s.date) = gp.fiscal_year
WHERE s.customer_code = @CustomerCode
  AND dbo.fn_GetFiscalYear(s.date) = @FiscalYear
ORDER BY s.date, s.product_code;

