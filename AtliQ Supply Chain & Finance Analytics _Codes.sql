Next up: AtliQ Hardware’s financial breakdown. Let’s figure out how AtliQ Hardware makes money! 
Here’s an illustrative example :- 
AtliQ sells a mouse to Croma for $30 gross price. That is the base price that AtliQ has set for this particular Mouse. Now there is some amount that needs to be deducted from this 
30$ because AtliQ sets a base gross price of $30 for a mouse sold to Croma. This is the full price, but Croma gets a special discount at the start of each year based on thier longstanding 
business relationship and the sales volume generated by the croma store for AtliQ. This pre-negotiated annual discount made at the beginning of each year is called as Pre-Invoice Deductions. 
Let’s assume the agreed discount for this mouse is $2, although it’s typically expressed as a percentage. Therefore, when AtliQ sells this mouse, Croma pays $28 instead of $30 after the deduction. 
This $28 is nothing but the Net Invoice Sales. 

After this process, Croma provides promotional offers to customers, facilitated by AtliQ Hardware. For instance, during festive seasons like Christmas or Diwali, AtliQ Hardware might suggest a 5% 
discount for the entire month as a promotional offer that Croma can extend to its consumers. So that is promotional offer. Discounts aren’t the only way AtliQ pushes their products. AtliQ wants 
their products to stand out, so they sometimes offer stores like Croma this premium discount or a bonus, called a “placement fees”, to put them at a prime location in the stores, hoping that this 
will draw more attention and boost their sales. This is a strategy to boost sales for AtliQ Hardware, especially considering that Croma may also source hardware from other manufacturers like Dell 
and HP. It’s all about getting their products noticed and bought! This is another way for them to compete with bigger brands and get their products noticed. Let’s say chroma is pretty good in selling 
these devices. They generate lot of sales for AliQ Hardware. So besides discounts like a base price discount, placement fees for prime locations, AtliQ can offer or rewards croma with other incentives 
or a bonus, called a “performance rebate” if the store sells a lot of their products. Basically, the more devices Croma sells, the more money they get back from AtliQ at the end of the quarter or a 
month or a year, which benefits both companies in the long run. It’s like a way of saying “Thank you for being a great sales partner! We appreciate your business!” After the initial pre-invoice sales 
price is set, there are 3 types of discounts AtliQ can use to further reduce the cost for stores like Croma. 

These 3 types of discounts that we discussed earlier come under the Post-invoice Deductions. Think of post-invoice deductions as adjustments made after the initial sale of a product. 
Post-invoice Deductions = festival sales discount or promotional offer discount from the consumer (i.e shoppers) + Platform fee from croma (i.e AtliQ’s customer) + Performance Rebates based on how well 
                          croma sell (i.e AtliQ’s customer). 
After AtliQ sells a mouse to Croma, there might be some savings and adjustments to the final price. We call these adjustments “Post-invoice deductions”. All these “Post-invoice deductions” add up to more 
profit for Croma on each AtliQ device they sell, further reducing the cost, creating a flexible pricing system! These adjustments can significantly lower the final cost for croma stores and hence AtliQ 
easily builds loyalty with stores like Croma through post-invoice adjustments. So, AtliQ sold mouse to croma for 28$ before Post-invoice deductions. At the end of the selling period (month or quarter or Year), 
they decide and come to agreement for Post-invoice deductions which amount to $3. We need to account for those Post-invoice deductions (discounts, fees and rebates) to get the Net Sales. To figure out Net 
Sales, we must deduct the Post-invoice deduction amount from the initial invoiced amount (Net Invoice 
Sales) paid by Croma. 
Net Sales actually defines the price of the product after considering all the deductions. 
Net Sales = Gross Price — (Pre-invoice deduction + Postinvoice deduction) 
Net Sales = (Gross Price — Pre-invoice deduction) — Postinvoice deduction 
Net Sales = Net invoice Sales — Post-invoice deduction 

So eventually at the end of the day AliQ is selling mouse to croma for $25, which is the revenue of AtliQ Hardware Technologies (Net Sales). After we cut those extra discounts from the initial invoiced 
amount (Net Invoice Sales) we get Net Sales amount. We now need to deduct the cost of goods sold(COGS) which includes the sum of : 
1. Manufacturing Cost 
2. Freight Cost (Transportation) 
3. Other expenses & costs 
from the Net Sales to get our gross profit. 
This tells us how much money we actually earned from selling the mouse to Croma. 

Suppose the COGS amount for this mouse is $20. After deducting the COGS amount from Net sales we get profit. $20 COGS means AtliQ Hardware earns a profit of $5 per mouse. 
That’s $5 for each mouse. This profit is also referred to as Gross Margin or Gross Margin on Net Sales. 
Gross Margin = Net Sales — Cost of Goods sold (COGS) 
Gross Margin as % of Net Sales = Gross Margin / Net Sales 
Hence Gross Margin comes out as 20% of Net Sales That means AtliQ Hardware make 20% profit on every mouse they sell ($5 profit divided by the $25 sale price), after accounting for the cost of making and shipping them. 
This is a quick summary of Profit and Loss statement. This summary is about the business model of the AtliQ, now we can move towards the tables. 

