-- ============================================================================
-- TASK 6
-- Analyze monthly forecast accuracy for a specific product over multiple
-- fiscal years using PIVOT. Forecast quantity and actual sold quantity are
-- presented side by side for each month.
-- ============================================================================

DECLARE @Task6ProductCode VARCHAR(45) = 'A0118150101';

WITH ForecastByMonth AS
(
    SELECT
        fiscal_year,
        MONTH(date) AS calendar_month,
        SUM(forecast_quantity) AS forecast_quantity
    FROM fact_forecast_monthly
    WHERE product_code = @Task6ProductCode
    GROUP BY fiscal_year, MONTH(date)
),
ActualByMonth AS
(
    SELECT
        dbo.fn_GetFiscalYear(date) AS fiscal_year,
        MONTH(date) AS calendar_month,
        SUM(sold_quantity) AS actual_quantity
    FROM fact_sales_monthly
    WHERE product_code = @Task6ProductCode
    GROUP BY dbo.fn_GetFiscalYear(date), MONTH(date)
),
Combined AS
(
    SELECT
        COALESCE(f.fiscal_year, a.fiscal_year) AS fiscal_year,
        COALESCE(f.calendar_month, a.calendar_month) AS calendar_month,
        ISNULL(f.forecast_quantity,0) AS forecast_quantity,
        ISNULL(a.actual_quantity,0) AS actual_quantity
    FROM ForecastByMonth f
    FULL OUTER JOIN ActualByMonth a
      ON f.fiscal_year = a.fiscal_year
     AND f.calendar_month = a.calendar_month
),
LongFormat AS
(
    SELECT fiscal_year, calendar_month, 'Forecast' AS metric, forecast_quantity AS quantity
    FROM Combined
    UNION ALL
    SELECT fiscal_year, calendar_month, 'Actual' AS metric, actual_quantity AS quantity
    FROM Combined
)
SELECT
    fiscal_year,
    calendar_month,
    ISNULL([Forecast],0) AS forecast_quantity,
    ISNULL([Actual],0) AS actual_quantity,
    CASE
      WHEN ISNULL([Forecast],0) = 0 THEN NULL
      ELSE ISNULL([Actual],0) * 100.0 / [Forecast]
    END AS forecast_accuracy_pct
FROM LongFormat
PIVOT
(
    SUM(quantity)
    FOR metric IN ([Forecast], [Actual])
) p
ORDER BY fiscal_year, calendar_month;
GO

/*
TASK 6 INTERPRETATION GUIDE
---------------------------
Forecast accuracy is calculated as:
    Actual Sold Quantity / Forecast Quantity * 100

- Around 100%: forecast closely matches actual demand.
- Below 100%: actual sales were lower than forecast (possible over-forecasting).
- Above 100%: actual sales exceeded forecast (possible under-forecasting).
- Missing forecast or sales values are retained through FULL OUTER JOIN and
  treated as zero where appropriate.
- Very high/low discrepancies can result from promotions, seasonality,
  stock-outs, new-product launches, customer behavior, or incomplete data.
*/


