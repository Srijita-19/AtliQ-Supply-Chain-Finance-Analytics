        PRIMARY KEY (product_code, cost_year),
    CONSTRAINT FK_manufacturing_product
        FOREIGN KEY (product_code) REFERENCES dim_product(product_code),
	CONSTRAINT CK_manufacturing_cost_nonnegative
        CHECK (manufacturing_cost >= 0)
